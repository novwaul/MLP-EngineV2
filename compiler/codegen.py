"""Schedule-to-LIR Lowering Pass and AST-Driven Code Generator for MLP-EngineV2.

Lowers a high-level `ProgramSchedule` (derived from an ONNX `ModelGraph` and
`MemoryPlan`) into structured Low-Level IR (`HeaderUnit` and `SourceUnit` ASTs in
`compiler/lir.py`), then visits the AST via `CCodeEmitter` to produce `mlp.h` and `mlp.c`.
"""

