def _build_min_u_lir() -> FunctionDecl:
    """Synthesize `static inline unsigned min_u(unsigned a, unsigned b)` LIR node."""
    a = VarRef("a")
    b = VarRef("b")
    return FunctionDecl(
        return_type="unsigned",
        name="min_u",
        params=[ParamDecl("unsigned", "a"), ParamDecl("unsigned", "b")],
        body=[ReturnStmt(TernaryOp(BinaryOp("<", a, b), a, b))],
        is_static=True,
        is_inline=True,
    )


def _build_pack_lir() -> FunctionDecl:
    """Synthesize 4-byte word-unrolled `pack(uint32_t *dst, uint32_t src, unsigned count)` LIR."""
    dst = VarRef("dst")
    src = VarRef("src")
    count = VarRef("count")
    s = VarRef("s")
    words = VarRef("words")
    w = VarRef("w")
    rem = VarRef("rem")
    word = VarRef("word")
    j = VarRef("j")
    mask_ff = IntImm(0xFF, hex_width=2, unsigned=True)

    byte0 = BinaryOp("&", Subscript(s, IntImm(0)), mask_ff)
    byte1 = BinaryOp("<<", BinaryOp("&", Subscript(s, IntImm(1)), mask_ff), IntImm(8))
    byte2 = BinaryOp("<<", BinaryOp("&", Subscript(s, IntImm(2)), mask_ff), IntImm(16))
    byte3 = BinaryOp("<<", BinaryOp("&", Subscript(s, IntImm(3)), mask_ff), IntImm(24))
    packed_word_expr = BinaryOp("|", BinaryOp("|", BinaryOp("|", byte0, byte1), byte2), byte3)

    unrolled_loop = ForStmt(
        init_type="unsigned",
        loop_var="w",
        start=IntImm(0),
        cond=BinaryOp("<", w, words),
        step_op="++",
        step_val=IntImm(1),
        extra_steps=[("s", "+=", IntImm(4))],
        body=[AssignStmt(Subscript(dst, w), packed_word_expr)],
    )

    rem_loop = ForStmt(
        init_type="unsigned",
        loop_var="j",
        start=IntImm(0),
        cond=BinaryOp("<", j, rem),
        step_op="++",
        step_val=IntImm(1),
        body=[
            AssignStmt(
                word,
                BinaryOp(
                    "<<",
                    BinaryOp("&", Subscript(s, j), mask_ff),
                    BinaryOp("<<", j, IntImm(3)),
                ),
                op="|=",
            )
        ],
    )

    rem_if = IfStmt(
        cond=rem,
        then_body=[
            VarDeclStmt("uint32_t", "word", IntImm(0)),
            rem_loop,
            AssignStmt(Subscript(dst, words), word),
        ],
    )

    return FunctionDecl(
        return_type="void",
        name="pack",
        params=[
            ParamDecl("uint32_t *", "dst"),
            ParamDecl("uint32_t", "src"),
            ParamDecl("unsigned", "count"),
        ],
        body=[
            VarDeclStmt(
                "const uint32_t *",
                "s",
                CastExpr("const uint32_t *", CastExpr("uintptr_t", src)),
            ),
            VarDeclStmt("unsigned", "words", BinaryOp(">>", count, IntImm(2))),
            unrolled_loop,
            VarDeclStmt("unsigned", "rem", BinaryOp("&", count, IntImm(3, unsigned=True))),
            rem_if,
        ],
        is_static=True,
        doc_comment="Word-unrolled 4-byte packer synthesized by mlpv2c.",
    )


def _lower_layer_schedule_to_lir(lsched: LayerSchedule) -> FunctionDecl:
    """Lower one ONNX `LayerSchedule` into a specialized C function AST `run_<layer>(unsigned m)`.

    Applies compile-time specialization from the ONNX layer dimensions:
      - Hoists `ACC_A_STRIDE`, `ACC_W_STRIDE`, `ACC_OUT_STRIDE` to the layer prologue.
      - When `tail_cols == 0` and `tail_k == 0` (e.g. 784->128, 128->64), hoists `ACC_SHAPE`
        out of the column loop into the layer prologue as well.
      - Eliminates dead tail-K conditional branches (`if (next + 16 > in_features)`) when
        `in_features % 16 == 0` (`tail_k == 0`).
      - Inserts `ACC_LAST` on the final K-tile when hardware ReLU + requantization is active.
    """
    layer = lsched.layer
    mem = lsched.mem
    lname = layer.name
    uname = lname.upper()

    in_macro = VarRef(f"{uname}_IN_SIZE")
    out_macro = VarRef(f"{uname}_OUT_SIZE")
    out_spad = VarRef(f"{uname}_O_ADDR")
    a_base: Expr = (
        VarRef(mem.input_addr_expr)
        if mem.input_is_spad
        else CallExpr("ADDR", (VarRef("input"),))
    )
    w_base = CallExpr("ADDR", (VarRef(f"{lname}_w"),))
    b_base = CallExpr("ADDR", (VarRef(f"{lname}_b"),))
    m_var = VarRef("m")
    col_var = VarRef("col")
    w_col_var = VarRef("w_col")
    bank_var = VarRef("bank")
    k_var = VarRef("k")
    next_var = VarRef("next")

    body: List[Stmt] = [
        AccCfgStmt("ACC_A_STRIDE", in_macro),
        AccCfgStmt("ACC_W_STRIDE", in_macro),
        AccCfgStmt("ACC_OUT_STRIDE", out_macro),
    ]

    first_k_len = lsched.col_blocks[0].k_tiles[0].k_len
    if lsched.shape_hoisted_to_layer:
        shape_imm = (HW_ARRAY_COLS << 4) | (first_k_len << 8)
        body.append(
            AccCfgStmt("ACC_SHAPE", BinaryOp("|", m_var, IntImm(shape_imm, hex_width=4)))
        )

    # Build column-block body
    col_body: List[Stmt] = [
        VarDeclStmt("uint32_t", "w_col", BinaryOp("+", w_base, BinaryOp("*", col_var, in_macro))),
        VarDeclStmt("unsigned", "bank", IntImm(0)),
    ]

    if not lsched.shape_hoisted_to_layer:
        if lsched.tail_cols != 0:
            col_body.append(
                VarDeclStmt(
                    "unsigned",
                    "n",
                    CallExpr("min_u", (IntImm(HW_ARRAY_COLS), BinaryOp("-", out_macro, col_var))),
                )
            )
            n_bits: Expr = BinaryOp("<<", VarRef("n"), IntImm(4))
        else:
            n_bits = IntImm(HW_ARRAY_COLS << 4, hex_width=2)

        if lsched.tail_k != 0:
            col_body.append(
                VarDeclStmt("uint32_t", "base_shape", BinaryOp("|", m_var, n_bits))
            )
            col_shape_expr: Expr = BinaryOp(
                "|", VarRef("base_shape"), IntImm(first_k_len << 8, hex_width=4)
            )
        else:
            col_shape_expr = BinaryOp(
                "|",
                BinaryOp("|", m_var, n_bits),
                IntImm(first_k_len << 8, hex_width=4),
            )

    col_body.extend([
        AccCfgStmt("ACC_BIAS", BinaryOp("+", b_base, col_var)),
        AccCfgStmt("ACC_OUT", BinaryOp("+", out_spad, col_var)),
        AccCfgStmt("ACC_A", a_base),
        AccCfgStmt("ACC_W", w_col_var),
    ])
    if not lsched.shape_hoisted_to_layer:
        col_body.append(AccCfgStmt("ACC_SHAPE", col_shape_expr))

    col_body.extend([
        AccLoadStmt(IntImm(0)),
        AccWaitStmt("ACC_WAIT_TRANSFER"),
    ])

    # Build K-tile loop (or single-tile execution if in_features <= 16)
    num_k_tiles = len(lsched.col_blocks[0].k_tiles)
    if num_k_tiles == 1:
        flags_expr: Expr = (
            BinaryOp("|", VarRef("ACC_FIRST"), VarRef("ACC_LAST"))
            if layer.has_relu
            else VarRef("ACC_FIRST")
        )
        col_body.extend([
            AccRunStmt(IntImm(0), flags_expr),
            AccWaitStmt("ACC_WAIT_ALL"),
            AccCheckErrStmt(-1),
        ])
    else:
        next_cfg_body: List[Stmt] = [
            AccCfgStmt("ACC_A", BinaryOp("+", a_base, next_var)),
            AccCfgStmt("ACC_W", BinaryOp("+", w_col_var, next_var)),
        ]
        if lsched.tail_k != 0:
            # Only emitted when in_features is not a multiple of 16
            rem_k_shift = BinaryOp("<<", BinaryOp("-", in_macro, next_var), IntImm(8))
            next_cfg_body.append(
                IfStmt(
                    cond=BinaryOp(">", BinaryOp("+", next_var, VarRef("ACC_K_TILE")), in_macro),
                    then_body=[
                        AccCfgStmt("ACC_SHAPE", BinaryOp("|", VarRef("base_shape"), rem_k_shift))
                    ],
                )
            )

        first_flag = TernaryOp(BinaryOp("==", k_var, IntImm(0)), VarRef("ACC_FIRST"), IntImm(0))
        if layer.has_relu:
            last_flag = TernaryOp(
                BinaryOp(">=", next_var, in_macro), VarRef("ACC_LAST"), IntImm(0)
            )
            run_flags_expr: Expr = BinaryOp("|", first_flag, last_flag)
        else:
            run_flags_expr = first_flag

        k_loop = ForStmt(
            init_type="unsigned",
            loop_var="k",
            start=IntImm(0),
            cond=BinaryOp("<", k_var, in_macro),
            step_op="+=",
            step_val=VarRef("ACC_K_TILE"),
            body=[
                VarDeclStmt("unsigned", "next", BinaryOp("+", k_var, VarRef("ACC_K_TILE"))),
                IfStmt(cond=BinaryOp("<", next_var, in_macro), then_body=next_cfg_body),
                AccRunStmt(bank_var, run_flags_expr),
                IfStmt(
                    cond=BinaryOp("<", next_var, in_macro),
                    then_body=[AccLoadStmt(BinaryOp("^", bank_var, IntImm(1)))],
                ),
                AccWaitStmt("ACC_WAIT_ALL"),
                AccCheckErrStmt(-1),
                AssignStmt(bank_var, IntImm(1), op="^="),
            ],
        )
        col_body.append(k_loop)

    col_body.extend([
        AccStoreStmt(),
        AccWaitStmt("ACC_WAIT_TRANSFER"),
        AccCheckErrStmt(-1),
    ])

    body.append(
        ForStmt(
            init_type="unsigned",
            loop_var="col",
            start=IntImm(0),
            cond=BinaryOp("<", col_var, out_macro),
            step_op="+=",
            step_val=IntImm(HW_ARRAY_COLS),
            body=col_body,
        )
    )
    body.append(ReturnStmt(IntImm(0)))

    doc = (
        f"Synthesized kernel for ONNX layer '{lname}' "
        f"({layer.in_features} -> {layer.out_features}, "
        f"ReLU={layer.has_relu}, tail_cols={lsched.tail_cols}, tail_k={lsched.tail_k}, "
        f"CFG saved={lsched.cfg_reduction_pct:.1f}%)."
    )
    return FunctionDecl(
        return_type="int",
        name=f"run_{lname}",
        params=[ParamDecl("unsigned", "m")],
        body=body,
        is_static=True,
        doc_comment=doc,
    )


def _build_main_lir(schedule: ProgramSchedule) -> FunctionDecl:
    """Synthesize `int main(void)` AST from `ProgramSchedule`."""
    graph = schedule.graph
    body: List[Stmt] = [
        VarDeclStmt("unsigned", "image_idx", IntImm(0)),
        VarDeclStmt("unsigned", "correct_count", IntImm(0)),
        WriteTestbenchRegStmt("x26", VarRef("image_idx")),
        WriteTestbenchRegStmt("x27", VarRef("correct_count")),
        VarDeclStmt("unsigned", "start_clow"),
        VarDeclStmt("unsigned", "start_chigh"),
        VarDeclStmt("unsigned", "start_ilow"),
        VarDeclStmt("unsigned", "start_ihigh"),
        VarDeclStmt("unsigned", "end_clow"),
        VarDeclStmt("unsigned", "end_chigh"),
        VarDeclStmt("unsigned", "end_ilow"),
        VarDeclStmt("unsigned", "end_ihigh"),
        CsrReadStmt("mcycle", "start_clow"),
        CsrReadStmt("mcycleh", "start_chigh"),
        CsrReadStmt("minstret", "start_ilow"),
        CsrReadStmt("minstreth", "start_ihigh"),
        CommentStmt("Pack ONNX initializers (weights & biases) into .noinit RAM"),
    ]

    for layer in graph.layers:
        uname = layer.name.upper()
        body.append(
            ExprStmt(
                CallExpr(
                    "pack",
                    (
                        VarRef(f"{layer.name}_w"),
                        VarRef(f"{uname}_W_ADDR"),
                        BinaryOp("*", VarRef(f"{uname}_IN_SIZE"), VarRef(f"{uname}_OUT_SIZE")),
                    ),
                )
            )
        )
    for layer in graph.layers:
        uname = layer.name.upper()
        body.append(
            ExprStmt(
                CallExpr(
                    "pack",
                    (
                        VarRef(f"{layer.name}_b"),
                        VarRef(f"{uname}_B_ADDR"),
                        VarRef(f"{uname}_OUT_SIZE"),
                    ),
                )
            )
        )

    # Batch inference loop body
    image_var = VarRef("image")
    m_var = VarRef("m")
    r_var = VarRef("r")
    c_var = VarRef("c")
    best_var = VarRef("best")
    o_var = VarRef("o")
    final_out_spad = VarRef(f"{graph.layers[-1].name.upper()}_O_ADDR")

    batch_body: List[Stmt] = [
        VarDeclStmt(
            "unsigned",
            "m",
            CallExpr(
                "min_u",
                (VarRef("ARRAY_SIZE"), BinaryOp("-", VarRef("NUM_OF_TEST"), image_var)),
            ),
        ),
        ExprStmt(
            CallExpr(
                "pack",
                (
                    VarRef("input"),
                    BinaryOp(
                        "+",
                        VarRef("INPUT_ADDR"),
                        BinaryOp(
                            "*",
                            BinaryOp("*", image_var, VarRef("INPUT_SIZE")),
                            IntImm(4),
                        ),
                    ),
                    BinaryOp("*", m_var, VarRef("INPUT_SIZE")),
                ),
            )
        ),
    ]

    # Emit calls to each synthesized layer function in topological order
    for lsched in schedule.layer_schedules:
        lname = lsched.layer.name
        batch_body.append(
            IfStmt(
                cond=CallExpr(f"run_{lname}", (m_var,)),
                then_body=[BreakStmt()],
            )
        )

    # Argmax over final output scratchpad buffer
    argmax_loop = ForStmt(
        init_type="unsigned",
        loop_var="r",
        start=IntImm(0),
        cond=BinaryOp("<", r_var, m_var),
        step_op="++",
        step_val=IntImm(1),
        body=[
            VarDeclStmt(
                "volatile const uint8_t *",
                "o",
                CastExpr(
                    "volatile const uint8_t *",
                    CastExpr(
                        "uintptr_t",
                        BinaryOp("+", final_out_spad, BinaryOp("*", r_var, VarRef("OUTPUT_SIZE"))),
                    ),
                ),
            ),
            VarDeclStmt("unsigned", "best", IntImm(0)),
            ForStmt(
                init_type="unsigned",
                loop_var="c",
                start=IntImm(1),
                cond=BinaryOp("<", c_var, VarRef("OUTPUT_SIZE")),
                step_op="++",
                step_val=IntImm(1),
                body=[
                    IfStmt(
                        cond=BinaryOp(">", Subscript(o_var, c_var), Subscript(o_var, best_var)),
                        then_body=[AssignStmt(best_var, c_var)],
                    )
                ],
            ),
            IfStmt(
                cond=BinaryOp(
                    "==",
                    best_var,
                    Subscript(VarRef("label"), BinaryOp("+", image_var, r_var)),
                ),
                then_body=[
                    ExprStmt(UnaryOp("++", VarRef("correct_count"), postfix=True))
                ],
            ),
        ],
    )

    batch_body.extend([
        argmax_loop,
        AssignStmt(VarRef("image_idx"), VarRef("ARRAY_SIZE"), op="+="),
        WriteTestbenchRegStmt("x27", VarRef("correct_count")),
        WriteTestbenchRegStmt("x26", VarRef("image_idx")),
    ])

    body.extend([
        VarDeclStmt(
            "const uint32_t *",
            "label",
            CastExpr("const uint32_t *", CastExpr("uintptr_t", VarRef("LABEL_ADDR"))),
        ),
        ForStmt(
            init_type="unsigned",
            loop_var="image",
            start=IntImm(0),
            cond=BinaryOp("<", image_var, VarRef("NUM_OF_TEST")),
            step_op="+=",
            step_val=VarRef("ARRAY_SIZE"),
            body=batch_body,
        ),
        CsrReadStmt("mcycle", "end_clow"),
        CsrReadStmt("mcycleh", "end_chigh"),
        CsrReadStmt("minstret", "end_ilow"),
        CsrReadStmt("minstreth", "end_ihigh"),
        VarDeclStmt("unsigned", "cycle_low", BinaryOp("-", VarRef("end_clow"), VarRef("start_clow"))),
        IfStmt(
            cond=BinaryOp(">", VarRef("cycle_low"), VarRef("end_clow")),
            then_body=[ExprStmt(UnaryOp("--", VarRef("end_chigh"), postfix=False))],
        ),
        VarDeclStmt("unsigned", "inst_low", BinaryOp("-", VarRef("end_ilow"), VarRef("start_ilow"))),
        IfStmt(
            cond=BinaryOp(">", VarRef("inst_low"), VarRef("end_ilow")),
            then_body=[ExprStmt(UnaryOp("--", VarRef("end_ihigh"), postfix=False))],
        ),
        WriteTestbenchRegStmt("x28", VarRef("cycle_low")),
        WriteTestbenchRegStmt("x29", BinaryOp("-", VarRef("end_chigh"), VarRef("start_chigh"))),
        WriteTestbenchRegStmt("x30", VarRef("inst_low")),
        WriteTestbenchRegStmt("x31", BinaryOp("-", VarRef("end_ihigh"), VarRef("start_ihigh"))),
        WriteTestbenchRegStmt("x25", VarRef("EXIT_MAGIC")),
        ReturnStmt(IntImm(0)),
    ])

    return FunctionDecl(
        return_type="int",
        name="main",
        params=[],
        body=body,
        is_static=False,
    )


def lower_to_source_lir(schedule: ProgramSchedule) -> SourceUnit:
    """Lower `ProgramSchedule` into a complete `SourceUnit` AST (`mlp.c`)."""
    graph = schedule.graph
    mplan = schedule.memory_plan
    decls: List[TopDecl] = [
        IncludeDecl("stdint.h", system=True),
        IncludeDecl("accel.h", system=False),
        IncludeDecl("mlp.h", system=False),
        DefineDecl("NOINIT", '__attribute__((section(".noinit"), aligned(4)))'),
        DefineDecl("SET_REG(reg, value)", '__asm__ volatile("mv " reg ", %0" :: "r"(value))'),
        DefineDecl("EXIT_MAGIC", IntImm(99999)),
        DefineDecl("ADDR(p)", "((uint32_t)(uintptr_t)(p))"),
    ]

    for b in mplan.layers:
        decls.append(StaticArrayDecl("uint32_t", f"{b.layer_name}_w", b.packed_w_words))
    for b in mplan.layers:
        decls.append(StaticArrayDecl("uint32_t", f"{b.layer_name}_b", b.packed_b_words))
    decls.append(StaticArrayDecl("uint32_t", "input", mplan.packed_input_words))

    decls.append(_build_min_u_lir())
    decls.append(_build_pack_lir())

    # Lower each scheduled ONNX layer into its own specialized C kernel AST
    for lsched in schedule.layer_schedules:
        decls.append(_lower_layer_schedule_to_lir(lsched))

    decls.append(_build_main_lir(schedule))

    shape_chain = " -> ".join(
        [str(graph.input_size)] + [str(l.out_features) for l in graph.layers]
    )
    return SourceUnit(
        banner_lines=[
            "Auto-generated by mlpv2c (MLP-EngineV2 Compiler)",
            f"Model: {graph.name} ({shape_chain})",
            f"CFG Optimization: {schedule.total_baseline_cfgs} -> {schedule.total_optimized_cfgs} "
            f"(-{schedule.total_cfg_reduction_pct:.1f}% ACC.CFG instructions per batch)",
        ],
        decls=decls,
    )


# =============================================================================
# 3. Top-Level Entry Points
# =============================================================================

def generate_mlp_h(schedule: ProgramSchedule, num_of_test: int = 10) -> str:
    emitter = CCodeEmitter()
    return emitter.emit_header_unit(lower_to_header_lir(schedule, num_of_test=num_of_test))


def generate_mlp_c(schedule: ProgramSchedule) -> str:
    emitter = CCodeEmitter()
    return emitter.emit_source_unit(lower_to_source_lir(schedule))


def generate_all(
    schedule: ProgramSchedule,
    num_of_test: int = 10,
) -> GeneratedArtifacts:
    emitter = CCodeEmitter()
    header_lir = lower_to_header_lir(schedule, num_of_test=num_of_test)
    source_lir = lower_to_source_lir(schedule)
    return GeneratedArtifacts(
        mlp_h=emitter.emit_header_unit(header_lir),
        mlp_c=emitter.emit_source_unit(source_lir),
        header_lir=header_lir,
        source_lir=source_lir,
    )


def write_generated_files(
    artifacts: GeneratedArtifacts,
    out_dir: Union[str, Path],
) -> Dict[str, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written: Dict[str, Path] = {}

    p_h = out / "mlp.h"
    p_h.write_text(artifacts.mlp_h, encoding="utf-8")
    written["mlp.h"] = p_h

    p_c = out / "mlp.c"
    p_c.write_text(artifacts.mlp_c, encoding="utf-8")
    written["mlp.c"] = p_c

    return written
